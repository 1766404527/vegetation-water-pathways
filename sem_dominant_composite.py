"""Combine the SEM direct- and total-effect dominance maps.

The source maps are generated by ``sem_dominant_png.py``.  This script keeps
their native resolution, adds unambiguous panel labels, and writes a white-
background 600-dpi composite suitable for the independent figure package.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


BASE = Path(__file__).resolve().parents[1]
SEM_DIR = BASE / "result1" / "sem_s"
DIRECT = SEM_DIR / "sem_dominant_d.png"
TOTAL = SEM_DIR / "sem_dominant_t.png"
OUTPUT = SEM_DIR / "Figure_10_SEM_dominance.png"

PANEL_GAP = 80
LABEL_X = 85
LABEL_Y = 45
LABEL_SIZE = 132


def label_font() -> ImageFont.FreeTypeFont | ImageFont.ImageFont:
    """Use a serif bold face consistent with the map typography."""

    candidates = (
        Path(r"C:\Windows\Fonts\timesbd.ttf"),
        Path(r"C:\Windows\Fonts\times.ttf"),
        Path(r"C:\Windows\Fonts\DejaVuSerif-Bold.ttf"),
    )
    for candidate in candidates:
        if candidate.exists():
            return ImageFont.truetype(str(candidate), LABEL_SIZE)
    return ImageFont.load_default()


def load_rgb(path: Path) -> Image.Image:
    if not path.exists():
        raise FileNotFoundError(f"Missing source figure: {path}")
    image = Image.open(path)
    if image.mode == "RGBA":
        background = Image.new("RGBA", image.size, "white")
        background.alpha_composite(image)
        return background.convert("RGB")
    return image.convert("RGB")


def main() -> None:
    direct = load_rgb(DIRECT)
    total = load_rgb(TOTAL)

    target_width = max(direct.width, total.width)
    if direct.width != target_width:
        direct = direct.resize(
            (target_width, round(direct.height * target_width / direct.width)),
            Image.Resampling.LANCZOS,
        )
    if total.width != target_width:
        total = total.resize(
            (target_width, round(total.height * target_width / total.width)),
            Image.Resampling.LANCZOS,
        )

    canvas = Image.new(
        "RGB",
        (target_width, direct.height + PANEL_GAP + total.height),
        "white",
    )
    canvas.paste(direct, (0, 0))
    total_y = direct.height + PANEL_GAP
    canvas.paste(total, (0, total_y))

    draw = ImageDraw.Draw(canvas)
    font = label_font()
    draw.text((LABEL_X, LABEL_Y), "a)", fill="black", font=font)
    draw.text((LABEL_X, total_y + LABEL_Y), "b)", fill="black", font=font)

    canvas.save(OUTPUT, format="PNG", dpi=(600, 600), optimize=True)
    print(f"Saved {OUTPUT} ({canvas.width} x {canvas.height} px, 600 dpi)")


if __name__ == "__main__":
    main()
